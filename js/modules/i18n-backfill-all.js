  function install() {
    const api = window.DomainI18n;
    if (!api || !api.dict) {
      console.warn('[i18n-backfill-all] Brak window.DomainI18n — plik musi być ładowany PO i18n-domain.js.');
      return false;
    }
    const merge = (lang, src) => {
      const d = api.dict[lang] || (api.dict[lang] = {});
      let added = 0;
      for (const k in src) if (!(k in d)) { d[k] = src[k]; added++; }
      return added;
    };
    const stats = { sk: merge('sk', SK), cs: merge('cs', CS), en: merge('en', EN), de: merge('de', DE), es: merge('es', ES) };
    stats.at = merge('at', DE);   // at i de dzielą obiekt słownika — zwykle 0
    console.info('[i18n-backfill-all] Dopisano kluczy:', stats);
    if (typeof api.apply === 'function') api.apply();
    return true;
  }

  if (!install()) document.addEventListener('DOMContentLoaded', install);
